/// Builds a "ptg" document with exactly \p node_count nodes.
///
/// The generator is a documented function of the index k:
///
///   node 0            utility_feed feed.0          (the only structural source)
///   node 1            switchgear  msb.0            (main switchboard)
///   per leg k         pdu.k  (pdu, floor)          fed from msb.0.output
///                     br.k   (circuit, branch)     contained by pdu.k
///                     lap.k  (load_attachment_point, single corded), fed by br.k
///   per spare j       pdu.extra.j  (pdu, floor)    fed from msb.0.output
///
/// node_count = 2 + 3 * legs + spare, so the caller chooses the exact size.
/// Every identity, every edge identity and the whole structure are pure
/// functions of the index; the document contains no clock, no random value and
/// no environment-dependent text.
std::string synthetic_document(std::size_t node_count, std::size_t& legs_out, std::size_t& spare_out,
                               std::size_t& edge_count_out) {
  const std::size_t remaining = node_count >= 2 ? node_count - 2 : 0;
  const std::size_t legs = remaining / 3;
  const std::size_t spare = remaining % 3;
  legs_out = legs;
  spare_out = spare;
  edge_count_out = 1 + legs * 4 + spare;

  std::string out;
  out.reserve(node_count * 96);
  out += "facility facility:bench@1\n\n";
  out += "provenance producer=power-topology-benchmarks/1.0.0 origin=authored witness=\"deterministic ";
  out += std::to_string(node_count);
  out += "-node workload\"\n\n";
  out += "node feed.0 utility_feed class=primary voltage=low_voltage\n";
  out += "node msb.0 switchgear kind=main_switchboard voltage=low_voltage\n";
  out += "edge e.feed.msb feeds feed.0.source -> msb.0.input\n";

  for (std::size_t index = 0; index < legs; ++index) {
    const std::string k = std::to_string(index);
    out += "node pdu.";
    out += k;
    out += " pdu kind=floor voltage=low_voltage\n";
    out += "node br.";
    out += k;
    out += " circuit kind=branch voltage=low_voltage in=pdu.";
    out += k;
    out += "\n";
    out += "node lap.";
    out += k;
    out += " load_attachment_point attachment=single_corded consumer=consumer:load-";
    out += k;
    out += "\n";
    out += "edge e.msb.pdu.";
    out += k;
    out += " feeds msb.0.output -> pdu.";
    out += k;
    out += ".input_a\n";
    out += "edge e.pdu.br.";
    out += k;
    out += " feeds pdu.";
    out += k;
    out += ".output -> br.";
    out += k;
    out += ".line\n";
    out += "edge e.br.lap.";
    out += k;
    out += " feeds br.";
    out += k;
    out += ".load -> lap.";
    out += k;
    out += ".attachment\n";
  }
  for (std::size_t index = 0; index < spare; ++index) {
    const std::string k = std::to_string(index);
    out += "node pdu.extra.";
    out += k;
    out += " pdu kind=floor voltage=low_voltage\n";
    out += "edge e.msb.pdu.extra.";
    out += k;
    out += " feeds msb.0.output -> pdu.extra.";
    out += k;
    out += ".input_a\n";
  }
  return out;
}

NodeId node_id(std::string_view spelling) {
  const auto parsed = NodeId::parse(spelling);
  if (!parsed.has_value()) {
    return NodeId{};
  }
  return parsed.value();
}

/// One scale of the workload.
struct Workload {
  std::size_t nodes = 0;
  std::size_t edges = 0;
  std::size_t legs = 0;
  std::string scale;
  std::string document;
  std::string canonical;
  Topology baseline;
  NodeId source;
  NodeId target;
};

StoreOptions store_options_for(const std::string& path) {
  StoreOptions options;
  options.root = path;
  options.mode = StoreMode::ReadWrite;
  options.create_if_missing = true;
  options.retained_generations = 4;
  options.idempotency_retention = 4;
  options.durable_flush = true;
  options.enable_fault_injection = false;
  return options;
}

/// Publishes \p count generations of the same body. Each publication carries a
/// distinct mutation identity and a distinct expected base, so the store really
/// commits a chain rather than replaying one attempt.
bool publish_generations(Store& store, const TopologyDraft& draft, const std::vector<MutationId>& mutations,
                         std::size_t count, std::string& error) {
  for (std::size_t index = 0; index < count; ++index) {
    const auto info = store.info();
    if (!info.has_value()) {
      error = info.error().to_string();
      return false;
    }
    PublicationRequest request;
    request.authority.epoch = info.value().epoch;
    request.authority.incarnation = info.value().incarnation;
    request.authority.expected_base = info.value().head;
    request.mutation = mutations[index];
    const auto ordinal = AttemptOrdinal::parse(1);
    if (!ordinal.has_value()) {
      error = "attempt ordinal";
      return false;
    }
    request.attempt = ordinal.value();
    request.draft = draft;
    const auto receipt = store.publish(request);
    if (!receipt.has_value()) {
      error = receipt.error().to_string();
      return false;
    }
    g_sink += receipt.value().generation.value();
  }
  return true;
}

