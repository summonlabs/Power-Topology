/// Observations sink. Keeps the measured work observable so no compiler can
/// delete it as dead code. Printed once in the summary.
volatile std::uint64_t g_sink = 0;

constexpr std::string_view kCleanupNotApplicable = "not_applicable";
constexpr std::string_view kCleanupRemoved = "removed";
constexpr std::string_view kCleanupFailed = "remove_failed";

/// One benchmarked operation at one scale.
struct Measurement {
  std::string label;
  std::string scale;
  std::size_t reps = 0;
  long long total_ns = 0;
  double mean_ns = 0.0;
  double ops_per_sec = 0.0;
  std::string evidence = "REAL";
  std::string cleanup = std::string(kCleanupNotApplicable);
  std::string reason;
};

/// A step reports the nanoseconds it actually spent on completed work.
using Step = std::function<bool(long long& elapsed_ns, std::string& error)>;

std::string token_of(std::string_view text) {
  std::string out;
  out.reserve(text.size());
  for (const char character : text) {
    const bool safe = (character >= 'a' && character <= 'z') || (character >= 'A' && character <= 'Z') ||
                      (character >= '0' && character <= '9') || character == '_' || character == '-' ||
                      character == '.' || character == '/';
    out.push_back(safe ? character : '_');
  }
  return out;
}

std::string fixed(double value) {
  std::ostringstream out;
  out.setf(std::ios::fixed);
  out.precision(3);
  out << value;
  return out.str();
}

std::string join_path(const std::string& root, const std::string& name) {
  return (std::filesystem::path(root) / name).string();
}

std::size_t remove_tree(const std::string& path) {
  std::error_code ignored;
  return std::filesystem::remove_all(path, ignored);
}

