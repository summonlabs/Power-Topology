// benchmarks - completed-operation benchmarks for the power_topology library.
//
// Every timed region contains the *whole* mandatory work of the operation it
// names, never a submission or enqueue step:
//
//   construct_validate_encode  import parse + full validation + build + canonical encode
//   canonical_encode_digest    canonical encode + SHA-256 over the encoded image
//   decode_revalidate          framed read + decode + re-validate + digest comparison
//   publish_durable_generation fresh store creation + validation + encode + staging
//                              write + flush + read-back verification + atomic rename
//                              + head/manifest commit + floor advance + residue retirement
//   load_head_generation       re-read + decode + re-validate + manifest digest check
//   verify_store               complete deep store verification (manifest, floor, every
//                              retained generation, canonical fixed point, accepted attempts)
//   dependency_path_query      structural path enumeration + source/dependency resolution
//
// The workload is generated by a documented, deterministic function of the index
// (see synthetic_document below): no randomness, no wall-clock seeding, no
// environment-dependent content, so two runs on the same host build the same
// topology and produce the same digest.
//
// Stores live under --root (default ./bench-out) and every store directory is
// removed before the program exits; the cleanup state is reported per
// measurement and again in the summary.

